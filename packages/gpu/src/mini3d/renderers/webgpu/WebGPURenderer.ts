/**
 * The format a context was configured with. `getConfiguration()` may throw in
 * implementations that predate the method, and a hand-rolled `GPUCanvasContext`
 * (headless test doubles) may not have it at all.
 */
function configuredFormat(context: GPUCanvasContext): GPUTextureFormat | null {
  try {
    const getConfiguration = (context as unknown as {
      getConfiguration?: () => GPUCanvasConfiguration;
    }).getConfiguration;
    return getConfiguration ? getConfiguration.call(context).format : null;
  } catch {
    return null;
  }
}

/** `true` when the geometry's own index buffer can drive the draw directly. */
function planUsesIndex(geometry: BufferGeometry, topology: GPUPrimitiveTopology): boolean {
  if (topology === 'line-strip' || topology === 'point-list') return false;
  return topologySupportsIndexed(topology) && geometry.index !== null;
}

/** A single `pass.draw*` range plus how the draw must index. */
interface DrawPlan {
  indexBuffer: GPUBuffer | null;
  indexFormat: GPUIndexFormat;
  ranges: { start: number; count: number }[];
  drawMode: DrawMode;
}

/**
 * Resolves how one geometry is drawn, including the index-buffer expansion for
 * the topologies WebGPU cannot index (see the file header):
 *
 * - `'line-strip'` (used by `LineLoop`) becomes a `line-list` over the
 *   generated `0,1, 1,2, 閳ヮ泦 index buffer.
 * - an indexed point cloud becomes a `point-list` over an identity index.
 *
 * Both expansions are cached per source-index version by `WgpuGeometries`.
 */
function planDraw(
  geometry: BufferGeometry,
  cache: WgpuGeometries,
  record: WgpuGeometryRecord,
  materialIndex: number,
  multiMaterial: boolean,
): DrawPlan {
  const drawMode = (geometry.drawMode ?? 'triangles') as DrawMode;
  const topology = TOPOLOGY_FOR_DRAW_MODE[drawMode] ?? 'triangle-list';
  const index = geometry.index;
  const drawStart = Math.max(geometry.drawRange.start, 0);
  const total = geometry.drawCount;
  const drawEnd = Number.isFinite(geometry.drawRange.count)
    ? Math.min(total, drawStart + Math.max(0, geometry.drawRange.count))
    : total;

  const groups = geometry.groups;
  const hasGroups = groups.length > 0;
  const ranges: { start: number; count: number }[] = [];
  if (hasGroups && multiMaterial) {
    // Only the groups belonging to this item's material slot are drawn. A single
    // material covers every group, so that case falls through to one range.
    for (const group of groups) {
      if (group.materialIndex !== materialIndex) continue;
      if (group.count <= 0) continue;
      const start = Math.max(group.start, 0);
      const count = Math.min(group.count, total - start);
      if (count > 0) ranges.push({ start, count });
    }
  } else if (drawEnd > drawStart) {
    ranges.push({ start: drawStart, count: drawEnd - drawStart });
  }

  if (drawMode === 'line-strip') {
    // A strip cannot be indexed in WebGPU, so the whole (possibly grouped)
    // range is expanded once into a line list.
    const first = hasGroups ? (ranges[0]?.start ?? 0) : drawStart;
    const last = hasGroups
      ? (ranges[ranges.length - 1]?.start ?? 0) + (ranges[ranges.length - 1]?.count ?? 0)
      : drawEnd;
    const vertexCount = Math.max(2, last - first);
    const expansion = cache.lineStripIndex(geometry, vertexCount);
    if (!expansion) return emptyPlan(drawMode);
    const segments = expansion.count - 1;
    return {
      indexBuffer: expansion.buffer,
      indexFormat: 'uint32',
      ranges: segments > 0 ? [{ start: 0, count: segments * 2 }] : [],
      drawMode,
    };
  }

  if (topology === 'point-list' && index) {
    const expansion = cache.pointsIndex(geometry, index.count);
    if (!expansion) return emptyPlan(drawMode);
    return {
      indexBuffer: expansion.buffer,
      indexFormat: 'uint32',
      ranges: hasGroups ? ranges : [{ start: 0, count: expansion.count }],
      drawMode,
    };
  }

  if (topologySupportsIndexed(topology) && index && record.index) {
    return {
      indexBuffer: record.index.buffer,
      indexFormat: record.index.format,
      ranges,
      drawMode,
    };
  }

  return { indexBuffer: null, indexFormat: 'uint16', ranges, drawMode };
}

function emptyPlan(drawMode: DrawMode): DrawPlan {
  return { indexBuffer: null, indexFormat: 'uint16', ranges: [], drawMode };
}

function primitiveStats(drawMode: DrawMode): [number, number] {
  switch (drawMode) {
    case 'points':
      return [1, 1];
    case 'lines':
      return [2, 2];
    case 'line-strip':
      return [2, 1];
    case 'triangle-strip':
      return [1, 1];
    case 'triangles':
    default:
      return [1, 3];
  }
}

/**
 * Opaque first, then transparent back-to-front, with `renderOrder` applied within
 * each group. Matches `WebGLRenderer.compareRenderItems`; ordering by
 * `renderOrder` first would draw a transparent object before the opaque geometry
 * behind it and break the blend.
 */
function compareRenderItems(a: RenderItem, b: RenderItem): number {
  if (a.transparent !== b.transparent) return a.transparent ? 1 : -1;
  if (a.order !== b.order) return a.order - b.order;
  return a.transparent ? b.z - a.z : a.z - b.z;
}

function clampDimension(value: number, max: number): number {
  if (!Number.isFinite(value) || value <= 0) return 1;
  return Math.max(1, Math.min(Math.floor(value), max));
}

function now(): number {
  if (typeof performance !== 'undefined' && typeof performance.now === 'function') {
    return performance.now();
  }
  return Date.now();
}

