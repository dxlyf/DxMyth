/**
 * WebGPU renderer for mini3d.
 *
 * Mirrors `WebGLRenderer`'s scene traversal, sorting, culling and material
 * interpretation so both backends produce the same image, but drives a
 * `GPUDevice` instead of a GL context.
 *
 * ## Deliberate differences from WebGL
 *
 * - **Clip-space depth**: `Matrix4.makePerspective`/`makeOrthographic` ignore
 *   `camera.coordinateSystem` (the parameter is `void`ed), so the projection
 *   matrix is remapped in *software* before upload: every camera matrix is
 *   pre-multiplied by `CLIP_SPACE_REMAP` (`z' = z*0.5 + w*0.5`) on its way into
 *   `FrameUniforms`. The camera's own `projectionMatrix` is never mutated, so
 *   `unproject()` and the WebGL backend keep working on the same camera.
 * - **`polygonOffset`**: WebGPU has no depth-bias state outside a shadow pass,
 *   so `material.polygonOffset*` is ignored here (documented no-op).
 * - **Pipeline creation is async**: the first frame that introduces a material
 *   combination skips that draw while `createRenderPipelineAsync()` runs. Use
 *   `await renderer.compile(scene, camera)` to pre-warm everything first.
 * - **Stencil**: not exposed; `parameters.stencil` is accepted but unused.
 *
 * ## Documented choices for the "pick one" decisions
 *
 * 1. *Topology expansion* 閳?`'line-strip'` and `points` are expanded into
 *    `'line-list'`/`'point-list'` by generating an **index buffer** (see
 *    `WgpuGeometries#expansion:lineStrip`): `0,1, 1,2, 2,3, 閳ヮ泦 and an identity
 *    map respectively. No vertex data is duplicated.
 * 2. *`flipY`* 閳?implemented by flipping pixel **rows on the CPU during upload**
 *    (canvas round-trip for image sources) rather than negating V, because
 *    negating V through `uvTransform` would flip the tangent basis used by the
 *    normal-map perturbation. See `WgpuTextures`.
 * 3. *Mipmaps* 閳?generated by a bundled **compute** box-filter chain; if the
 *    device cannot run it, mipmapped `minFilter`s degrade to `'linear'` and a
 *    warning is emitted once.
 * 4. *Texture background* 閳?a tiny purpose-built WGSL fullscreen blit inside
 *    this backend (`BACKGROUND_WGSL` in `WgpuPipelines.ts`), sampled with
 *    V-down UVs so an unflipped background image appears right way up.
 */

